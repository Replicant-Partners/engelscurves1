// Builds data/dollarStreet.ts from the live Dollar Street API capture (families_raw.json).
// Metric: dollars/month = household consumption per adult-equivalent, PPP (Dollar Street docs).
import fs from 'node:fs';
const dir = new URL('.', import.meta.url);
const raw = JSON.parse(fs.readFileSync(new URL('families_raw.json', dir), 'utf8'));
const fams = raw.filter((f) => Number.isFinite(+f.sortVal)).map((f) => ({ c2: f.country.id, income: +(+f.sortVal).toFixed(1) }));
const dropped = raw.length - fams.length;
const OURS = { et: 'ETH', in: 'IND', ph: 'PHL', za: 'ZAF', id: 'IDN', vn: 'VNM', eg: 'EGY', co: 'COL', br: 'BRA', mx: 'MEX', ar: 'ARG', tr: 'TUR' };
const NAMES = { ETH: 'Ethiopia', IND: 'India', PHL: 'Philippines', ZAF: 'South Africa', IDN: 'Indonesia', VNM: 'Vietnam', EGY: 'Egypt', COL: 'Colombia', BRA: 'Brazil', MEX: 'Mexico', ARG: 'Argentina', TUR: 'Turkiye' };
const med = (v) => v[Math.floor(v.length / 2)];
const markets = Object.entries(OURS).map(([c2, iso3]) => {
  const v = fams.filter((f) => f.c2 === c2).map((f) => f.income).sort((a, b) => a - b);
  return { iso3, c2, country: NAMES[iso3], n: v.length, incomes: v, median: v.length ? +med(v).toFixed(0) : null, min: v.length ? +v[0].toFixed(0) : null, max: v.length ? +v[v.length - 1].toFixed(0) : null };
}).sort((a, b) => (a.median ?? 1e9) - (b.median ?? 1e9));
const all = fams.map((f) => f.income).sort((a, b) => a - b);
const out = {
  fetched: '2026-10-22', source: 'api.dollarstreet.org/v1/search/families (8 pages)',
  totalFamilies: raw.length, usable: fams.length, droppedNoIncome: dropped,
  globalIncomes: all.map((v) => +v.toFixed(0)),
  kharasMonthly: 335, // $11/day x 30.44 = $334.8, 2011 PPP (evidence item 13) - approximate unit bridge
  markets,
};
fs.writeFileSync(new URL('../../data/dollarStreet.ts', dir),
  '// Generated by analysis/dollar-street/build.mjs. Do not edit by hand.\n' +
  '// Dollar Street (Gapminder), CC BY 4.0. dollars/month = consumption per adult-equivalent, PPP.\n' +
  'export interface DsMarket { iso3: string; c2: string; country: string; n: number; incomes: number[]; median: number | null; min: number | null; max: number | null }\n' +
  'export interface DsData { fetched: string; source: string; totalFamilies: number; usable: number; droppedNoIncome: number; globalIncomes: number[]; kharasMonthly: number; markets: DsMarket[] }\n' +
  'export const dollarStreet: DsData = ' + JSON.stringify(out) + ';\n');
console.log(JSON.stringify({ total: raw.length, usable: fams.length, dropped, markets: markets.map((m) => `${m.iso3}:${m.n}@${m.median ?? '-'}`).join(' ') }));
