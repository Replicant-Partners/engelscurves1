// Builds data/explorerData.ts for /explorer.
// Observed: USDA ERS food share (via OWID) x World Bank GDP pc PPP 2021$ x WB population, 2017-2023.
// Projected 2024-2030: GDP moves on the IMF WEO NGDPRPPPPC ratio from the WB 2023 level;
// food share and population are HELD at 2023 (no invented shares) and flagged projected.
import fs from 'node:fs';
const dir = new URL('.', import.meta.url);
const rows = JSON.parse(fs.readFileSync(new URL('panel_2017_2023.json', dir), 'utf8'));
const weo = Object.fromEntries(JSON.parse(fs.readFileSync(new URL('imf_weo_NGDPRPPPPC_2023_2031.json', dir), 'utf8')).map((d) => [d.iso3, d.y]));

const lin = (d) => { const n = d.length, mx = d.reduce((s, p) => s + p.x, 0) / n, my = d.reduce((s, p) => s + p.y, 0) / n;
  let sxx = 0, sxy = 0, sst = 0; for (const p of d) { sxx += (p.x - mx) ** 2; sxy += (p.x - mx) * (p.y - my); sst += (p.y - my) ** 2; }
  const b = sxy / sxx, a = my - b * mx; const ssr = d.reduce((s, p) => s + (p.y - a - b * p.x) ** 2, 0);
  return { a, b, r2: 1 - ssr / sst, ssr, n }; };
const solve3 = (A, v) => { const M = A.map((r, i) => [...r, v[i]]);
  for (let c = 0; c < 3; c++) { let p = c; for (let r = c + 1; r < 3; r++) if (Math.abs(M[r][c]) > Math.abs(M[p][c])) p = r; [M[c], M[p]] = [M[p], M[c]];
    for (let r = 0; r < 3; r++) if (r !== c) { const k = M[r][c] / M[c][c]; for (let j = c; j < 4; j++) M[r][j] -= k * M[c][j]; } }
  return M.map((r, i) => r[3] / r[i]); };
const pw = (d) => { const xs = d.map((p) => p.x).sort((a, b) => a - b), lo = xs[Math.floor(0.15 * xs.length)], hi = xs[Math.floor(0.85 * xs.length)];
  let best = null; for (let k = lo; k <= hi; k += 0.01) { const X = d.map((p) => [1, p.x, Math.max(0, p.x - k)]);
    const A = [0, 1, 2].map((i) => [0, 1, 2].map((j) => X.reduce((s, r) => s + r[i] * r[j], 0)));
    const v = [0, 1, 2].map((i) => X.reduce((s, r, n) => s + r[i] * d[n].y, 0));
    const be = solve3(A, v); const ssr = X.reduce((s, r, n) => s + (d[n].y - (be[0] + be[1] * r[1] + be[2] * r[2])) ** 2, 0);
    if (!best || ssr < best.ssr) best = { k, ssr, be }; }
  const l = lin(d); return { knot: Math.exp(best.k), c0: best.be[0], c1: best.be[1], c2: best.be[2], supF: (l.ssr - best.ssr) / (best.ssr / (d.length - 3)), lin: l }; };

const d23 = rows.filter((r) => r.year === 2023).map((r) => ({ x: Math.log(r.gdp), y: r.share }));
const f = pw(d23);
const shareAtPw = (g) => { const x = Math.log(g); return f.c0 + f.c1 * x + f.c2 * Math.max(0, x - Math.log(f.knot)); };
// Transition end for the USDA lens: where the piecewise 2023 fit crosses 35%.
const end = Math.exp((0.35 - (f.c0 - f.c2 * Math.log(f.knot))) / (f.c1 + f.c2));
const usdaCurve = [1500, 3000, 5000, Math.round(f.knot), 12000, 20000, 35000, 60000, 100000].map((g) => ({ gdp: g, share: +shareAtPw(g).toFixed(4) }));

const projected = [];
for (const iso of new Set(rows.map((r) => r.iso3))) {
  const base = rows.find((r) => r.iso3 === iso && r.year === 2023); const w = weo[iso];
  if (!base || !w || w['2023'] == null) continue;
  for (let y = 2024; y <= 2030; y++) { if (w[String(y)] == null) continue;
    projected.push({ iso3: iso, name: base.name, region: base.region, year: y, share: base.share, gdp: Math.round(base.gdp * (w[String(y)] / w['2023'])), pop: base.pop, projected: true }); }
}

const out = {
  observed: rows,
  projected,
  usda: { year: 2023, n: f.lin.n, knot: Math.round(f.knot), supF: +f.supF.toFixed(1), end: Math.round(end),
    linA: +f.lin.a.toFixed(4), linB: +f.lin.b.toFixed(4), r2: +f.lin.r2.toFixed(3), curve: usdaCurve },
};
const header = '// Generated by analysis/explorer/build_explorer_data.mjs. Do not edit by hand.\n' +
  '// Observed: USDA ERS food share (OWID download) x World Bank NY.GDP.PCAP.PP.KD x SP.POP.TOTL, 2017-2023.\n' +
  '// Projected 2024-2030: GDP on IMF WEO growth from the WB 2023 level; share and population HELD at 2023.\n' +
  'export interface ExplorerRow { iso3: string; name: string; region: string; year: number; share: number; gdp: number; pop: number; projected?: boolean }\n' +
  'export interface ExplorerData { observed: ExplorerRow[]; projected: ExplorerRow[]; usda: { year: number; n: number; knot: number; supF: number; end: number; linA: number; linB: number; r2: number; curve: { gdp: number; share: number }[] } }\n';
fs.writeFileSync(new URL('../../data/explorerData.ts', dir), header + 'export const explorer: ExplorerData = ' + JSON.stringify(out) + ';\n');
console.log(JSON.stringify({ observed: rows.length, projected: projected.length, usda: out.usda }, null, 1).slice(0, 700));
